CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_username CHECK (
        char_length(username) BETWEEN 3 AND 50
        AND username = lower(btrim(username))),
    CONSTRAINT ck_users_email CHECK (
        email = lower(btrim(email)) AND email <> ''),
    CONSTRAINT ck_users_password CHECK (password_hash <> ''),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE genres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    CONSTRAINT uq_genres_name UNIQUE (name),
    CONSTRAINT ck_genres_name CHECK (
        char_length(btrim(name)) BETWEEN 1 AND 50
        AND name = lower(btrim(name)))
);

CREATE TABLE movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(5000),
    release_year INTEGER NOT NULL,
    duration_minutes INTEGER NOT NULL,
    poster_url VARCHAR(1000),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_movies_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_movies_year CHECK (
        release_year BETWEEN 1888 AND 2100),
    CONSTRAINT ck_movies_duration CHECK (
        duration_minutes BETWEEN 1 AND 1500)
);

CREATE TABLE movie_genres (
    movie_id BIGINT NOT NULL REFERENCES movies(id)
        ON DELETE RESTRICT,
    genre_id BIGINT NOT NULL REFERENCES genres(id)
        ON DELETE RESTRICT,
    PRIMARY KEY (movie_id, genre_id)
);

CREATE TABLE ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id)
        ON DELETE RESTRICT,
    movie_id BIGINT NOT NULL REFERENCES movies(id)
        ON DELETE RESTRICT,
    score INTEGER NOT NULL,
    CONSTRAINT ck_ratings_score CHECK (score BETWEEN 1 AND 10),
    CONSTRAINT uq_ratings_user_movie UNIQUE (user_id, movie_id)
);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id)
        ON DELETE RESTRICT,
    movie_id BIGINT NOT NULL REFERENCES movies(id)
        ON DELETE RESTRICT,
    content VARCHAR(5000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_reviews_content CHECK (
        char_length(btrim(content)) BETWEEN 10 AND 5000),
    CONSTRAINT uq_reviews_user_movie UNIQUE (user_id, movie_id)
);

CREATE TABLE watchlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id)
        ON DELETE RESTRICT,
    movie_id BIGINT NOT NULL REFERENCES movies(id)
        ON DELETE RESTRICT,
    added_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_watchlist_user_movie UNIQUE (user_id, movie_id)
);

CREATE TABLE watched_movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id)
        ON DELETE RESTRICT,
    movie_id BIGINT NOT NULL REFERENCES movies(id)
        ON DELETE RESTRICT,
    watched_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_watched_user_movie UNIQUE (user_id, movie_id)
);

CREATE TABLE favorite_movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id)
        ON DELETE RESTRICT,
    movie_id BIGINT NOT NULL REFERENCES movies(id)
        ON DELETE RESTRICT,
    added_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_favorites_user_movie UNIQUE (user_id, movie_id)
);

CREATE INDEX idx_ratings_movie ON ratings (movie_id);
CREATE INDEX idx_reviews_movie ON reviews (movie_id);
CREATE INDEX idx_movie_genres_genre
    ON movie_genres (genre_id, movie_id);
CREATE INDEX idx_watchlist_movie ON watchlist_items (movie_id);
CREATE INDEX idx_watched_movie ON watched_movies (movie_id);
CREATE INDEX idx_favorites_movie ON favorite_movies (movie_id);
